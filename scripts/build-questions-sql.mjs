// Validates content/questions.json and writes supabase/seed_questions.sql.
//   npm run questions
// The generated SQL only inserts rows that are missing, so it is safe to re-run
// after adding questions. It never deletes or edits rows already in the table.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(root, "content/questions.json"), "utf8"));

const MODES = ["ONLINE", "OFFLINE"];
const INTENSITIES = ["PLAYFUL", "PERSONAL", "FLIRTY", "WILD", "AFTER DARK"];
const KINDS = ["TRUTH", "DARE"];
const CATEGORIES = ["Icebreakers", "Funny", "Personal", "Relationships", "Bold", "Challenges"];
const MIN_PER_BUCKET = 8;
const MIN_SOLO_PER_BUCKET = 4;
const MAX_LENGTH = 180;

// Guards against mixing the two modes by accident.
const OFFLINE_FORBIDDEN =
  /\b(chat|text|message|messages|voice note|camera|video|photo|selfie|emoji|emojis|online|phone|internet|call|search(ed)?|screen|post)\b/i;
const ONLINE_FORBIDDEN =
  /\b(in this room|across the room|in the room|sitting here|the room|hold hands|high-five|whisper|dance|sway|sing a made-up|group pose|star jumps|balance a book)\b/i;
// Solo items must not depend on other people.
const SOLO_FORBIDDEN = /\b(another player|other player|the others|the group|someone here|someone in|players? here|who here|whoever|everyone|another person)\b/i;
// Nothing that pushes dangerous, illegal or sensitive-data content.
const UNSAFE =
  /\b(alcohol|drunk|shot of|drink a|jump off|climb|knife|fire|lighter|drug|steal|break into|password|address|bank|credit card|ex-?partner|nude|naked|strip|kiss)\b/i;

const problems = [];
const rows = [];
const seen = new Set();

for (const mode of MODES) {
  for (const intensity of INTENSITIES) {
    for (const kind of KINDS) {
      const list = data?.[mode]?.[intensity]?.[kind];
      if (!Array.isArray(list)) {
        problems.push(`${mode}/${intensity}/${kind}: missing`);
        continue;
      }
      let solo = 0;
      for (const [category, soloOk, body] of list) {
        const where = `${mode}/${intensity}/${kind} "${body}"`;
        if (!CATEGORIES.includes(category)) problems.push(`${where}: bad category ${category}`);
        if (typeof body !== "string" || !body.trim()) problems.push(`${where}: empty text`);
        if (body.length > MAX_LENGTH) problems.push(`${where}: longer than ${MAX_LENGTH}`);
        if (mode === "OFFLINE" && OFFLINE_FORBIDDEN.test(body)) problems.push(`${where}: Offline item mentions technology`);
        if (mode === "ONLINE" && ONLINE_FORBIDDEN.test(body)) problems.push(`${where}: Online item needs physical presence`);
        if (soloOk && SOLO_FORBIDDEN.test(body)) problems.push(`${where}: solo item mentions other people`);
        if (UNSAFE.test(body)) problems.push(`${where}: matches the safety filter`);
        const key = `${mode}|${intensity}|${kind}|${body.toLowerCase()}`;
        if (seen.has(key)) problems.push(`${where}: duplicate`);
        seen.add(key);
        if (soloOk) solo += 1;
        rows.push({ mode, intensity, kind, category, soloOk: Boolean(soloOk), body });
      }
      if (list.length < MIN_PER_BUCKET) problems.push(`${mode}/${intensity}/${kind}: only ${list.length} items`);
      if (solo < MIN_SOLO_PER_BUCKET) problems.push(`${mode}/${intensity}/${kind}: only ${solo} solo-friendly items`);
    }
  }
}

if (problems.length) {
  console.error("Question content has problems:\n - " + problems.join("\n - "));
  process.exit(1);
}

const esc = (s) => s.replace(/'/g, "''");
const values = rows
  .map((r) => `  ('${r.mode}','${r.kind}','${esc(r.intensity)}','${r.category}',${r.soloOk},'${esc(r.body)}')`)
  .join(",\n");

const sql = `-- GENERATED by scripts/build-questions-sql.mjs from content/questions.json. Do not edit by hand.
-- Inserts only missing questions; never deletes or changes existing rows.
-- ${rows.length} questions: ${MODES.join(" + ")} x ${INTENSITIES.length} intensities x Truth/Dare.
insert into questions (mode, kind, intensity, category, solo_ok, body)
select v.mode, v.kind, v.intensity, v.category, v.solo_ok, v.body
from (values
${values}
) as v(mode, kind, intensity, category, solo_ok, body)
where not exists (
  select 1 from questions q
  where q.mode = v.mode and q.kind = v.kind and q.intensity = v.intensity and q.body = v.body
);
`;

writeFileSync(join(root, "supabase/seed_questions.sql"), sql);
console.log(`OK: ${rows.length} questions written to supabase/seed_questions.sql`);
